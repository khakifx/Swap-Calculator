export const SYMBOLS_DATABASE: SymbolData[] = SYMBOLS_DATA.map((item) => ({
  symbol: item.name,
  name: item.displayName,
  category: item.category === 'indices_commodities' ? 'indices' : item.category,
  contractSize: item.contractSize,
  digits: item.digits,
  point: item.pointSize,
  defaultSwapLongPoints: item.defaultSwapLongPoints,
  defaultSwapShortPoints: item.defaultSwapShortPoints,
  quoteCurrency: item.quoteCurrency,
  baseCurrency: item.baseCurrency,
  defaultQuoteToUsd: item.quoteToUsdRate,
  description: item.descriptionFa,
}));

export function getSymbolByCode(symbolCode: string): SymbolData | undefined {
  return SYMBOLS_DATABASE.find(
    (s) => s.symbol.toLowerCase() === symbolCode.trim().toLowerCase()
  );
}
